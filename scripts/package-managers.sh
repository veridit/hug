#!/usr/bin/env bash
# Write Homebrew formulas and Scoop manifests for a hug release into a tap
# checkout. Usage: scripts/package-managers.sh v0.7.0 dist/SHA256SUMS <tap-dir>
#
# hug.rb installs hug and its part names (muninn, huginn). muninn.rb and
# huginn.rb become small formulas that depend on hug, so machines that
# installed the parts before hug get hug on their next brew upgrade.
set -euo pipefail
ver="${1:?version}"; sums="${2:?SHA256SUMS}"; tap="${3:?tap dir}"
v="${ver#v}"
base="https://github.com/veridit/hug/releases/download/${ver}"
sha() { awk -v f="$1" '$2==f {print $1}' "$sums"; }
need() { [ -n "$(sha "$1")" ] || { echo "missing $1 in $sums" >&2; exit 1; }; }
for f in darwin_arm64.tar.gz darwin_amd64.tar.gz linux_arm64.tar.gz linux_amd64.tar.gz windows_amd64.zip windows_arm64.zip; do
  need "hug_${v}_${f}"
done
mkdir -p "$tap/Formula" "$tap/bucket"

cat > "$tap/Formula/hug.rb" <<EOF
# Generated by veridit/hug scripts/package-managers.sh for ${ver}. Do not edit.
class Hug < Formula
  desc "Memory and tasks for AI coding agents and people, in every harness"
  homepage "https://github.com/veridit/hug"
  version "${v}"
  license "MPL-2.0"

  on_macos do
    on_arm do
      url "${base}/hug_${v}_darwin_arm64.tar.gz"
      sha256 "$(sha "hug_${v}_darwin_arm64.tar.gz")"
    end
    on_intel do
      url "${base}/hug_${v}_darwin_amd64.tar.gz"
      sha256 "$(sha "hug_${v}_darwin_amd64.tar.gz")"
    end
  end

  on_linux do
    on_arm do
      url "${base}/hug_${v}_linux_arm64.tar.gz"
      sha256 "$(sha "hug_${v}_linux_arm64.tar.gz")"
    end
    on_intel do
      url "${base}/hug_${v}_linux_amd64.tar.gz"
      sha256 "$(sha "hug_${v}_linux_amd64.tar.gz")"
    end
  end

  def install
    bin.install "hug"
    bin.install_symlink "hug" => "muninn"
    bin.install_symlink "hug" => "huginn"
  end

  service do
    run [opt_bin/"hug", "mem", "serve"]
    keep_alive true
    log_path var/"log/hug.log"
    error_log_path var/"log/hug.log"
  end

  def caveats
    <<~EOS
      In a repository, see what is still needed:
        hug setup
      Wire memory into your agents (keeps backups, idempotent):
        hug mem install all
      Keep the memory index fresh in the background:
        brew services start hug
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/hug version")
    assert_match "muninn", shell_output("#{bin}/muninn version")
  end
end
EOF

for part in muninn huginn; do
  cls="$(tr '[:lower:]' '[:upper:]' <<< "${part:0:1}")${part:1}"
  cat > "$tap/Formula/$part.rb" <<EOF
# Generated by veridit/hug scripts/package-managers.sh for ${ver}. Do not edit.
# ${part} is now part of hug; this formula installs hug, which provides ${part}.
class ${cls} < Formula
  desc "Now part of hug: brew install veridit/tap/hug"
  homepage "https://github.com/veridit/hug"
  url "${base}/SHA256SUMS"
  version "${v}"
  sha256 "$(shasum -a 256 "$sums" | awk '{print $1}')"
  license "MPL-2.0"

  depends_on "veridit/tap/hug"

  def install
    (share/"${part}").install "SHA256SUMS" => "release-sums"
  end

  def caveats
    <<~EOS
      ${part} is now part of hug. The ${part} command comes from the hug formula.
      You can switch with: brew uninstall ${part} (hug stays installed).
    EOS
  end

  test do
    assert_match "${part}", shell_output("#{Formula["veridit/tap/hug"].opt_bin}/${part} version")
  end
end
EOF
done

cat > "$tap/bucket/hug.json" <<EOF
{
    "version": "${v}",
    "description": "Memory and tasks for AI coding agents and people, in every harness",
    "homepage": "https://github.com/veridit/hug",
    "license": "MPL-2.0",
    "architecture": {
        "64bit": {
            "url": "${base}/hug_${v}_windows_amd64.zip",
            "hash": "$(sha "hug_${v}_windows_amd64.zip")",
            "extract_dir": "hug_${v}_windows_amd64"
        },
        "arm64": {
            "url": "${base}/hug_${v}_windows_arm64.zip",
            "hash": "$(sha "hug_${v}_windows_arm64.zip")",
            "extract_dir": "hug_${v}_windows_arm64"
        }
    },
    "bin": ["hug.exe", "muninn.exe", "huginn.exe"],
    "checkver": "github",
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "https://github.com/veridit/hug/releases/download/v\$version/hug_\$version_windows_amd64.zip",
                "extract_dir": "hug_\$version_windows_amd64"
            },
            "arm64": {
                "url": "https://github.com/veridit/hug/releases/download/v\$version/hug_\$version_windows_arm64.zip",
                "extract_dir": "hug_\$version_windows_arm64"
            }
        },
        "hash": { "url": "https://github.com/veridit/hug/releases/download/v\$version/SHA256SUMS" }
    }
}
EOF
echo "wrote hug, muninn, huginn formulas and hug.json for ${ver}"
